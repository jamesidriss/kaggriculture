"""Build reports/TOP_META_TABLE.md from the canonical per-game rows.

Sorted by EVIDENCE (direct head-to-head record against the two top agents),
never by a historical Kaggle notebook score. A published score is context, not
a measurement, and the two are kept in separate columns.
"""
import csv
import glob
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "benchmark"))
from stats import wilson, win_interval  # noqa: E402

OUT = os.path.join(ROOT, "reports", "TOP_META_TABLE.md")
CATALOG = os.path.join(ROOT, "research", "FINAL_PUBLIC_AGENT_CATALOG.csv")
RESULTS = os.path.join(ROOT, "experiments", "final_meta_results.csv")
PRIMARY_SHA = "c1e3590d02e42d16091c5377e87a3db16496e5a462d558dc2925887f835f9891"
HEDGE_SHA = "bfee70e9daaebeae0737a880f1df8f1c60d0783c59af620136cc0d28ef482bc7"


def main():
    meta = {}
    for row in csv.DictReader(open(CATALOG, encoding="utf-8")):
        meta[row["agent_name"]] = row

    rows = list(csv.DictReader(open(RESULTS, encoding="utf-8")))
    valid = [r for r in rows if r["valid"] == "1"]

    # Digest -> display name, shortest label wins.
    label = {}
    for r in valid:
        for d, n in ((r["candidate_sha"], r["candidate_name"]),
                     (r["opponent_sha"], r["opponent_name"])):
            if d not in label or len(n) < len(label[d]):
                label[d] = n

    # Direct record of every agent against PRIMARY and against HEDGE.
    def vs(target_sha):
        out = defaultdict(lambda: [0, 0, 0, 0])
        for r in valid:
            if r["opponent_sha"] == target_sha and r["candidate_sha"] != target_sha:
                e = out[r["candidate_sha"]]
                e[0] += int(r["win"]); e[1] += int(r["loss"])
                e[2] += int(r["tie"]); e[3] += 1
            elif r["candidate_sha"] == target_sha and r["opponent_sha"] != target_sha:
                e = out[r["opponent_sha"]]
                e[0] += int(r["loss"]); e[1] += int(r["win"])
                e[2] += int(r["tie"]); e[3] += 1
        return out

    pv, hv = vs(PRIMARY_SHA), vs(HEDGE_SHA)

    # Any-vs-anything record, for the overall column.
    anyv = defaultdict(lambda: [0, 0, 0, 0])
    for r in valid:
        a, b = r["candidate_sha"], r["opponent_sha"]
        if a == b:
            continue
        for me, opp, w, l, t in ((a, b, r["win"], r["loss"], r["tie"]),
                                 (b, a, r["loss"], r["win"], r["tie"])):
            e = anyv[me]
            e[0] += int(w); e[1] += int(l); e[2] += int(t); e[3] += 1

    med = defaultdict(list)
    rt = defaultdict(list)
    for r in valid:
        med[r["candidate_sha"]].append(int(r["candidate_cash"]))
        for k in ("candidate_runtime_max", "opponent_runtime_max"):
            try:
                rt[r["candidate_sha"]].append(float(r[k]))
            except ValueError:
                pass

    agents = set(pv) | set(hv) | set(anyv)
    agents.add(PRIMARY_SHA)
    agents.add(HEDGE_SHA)

    def cell(sha, tbl):
        w, l, t, n = tbl.get(sha, [0, 0, 0, 0])
        if n == 0:
            return "not measured", ""
        iv = win_interval(w, l, t)
        return (f"{w}-{l}-{t} /{n}", f"{iv['win_rate']:.3f} "
                f"[{iv['wilson_lo']:.3f}, {iv['wilson_hi']:.3f}]")

    def sort_key(sha):
        e = pv.get(sha, [0, 0, 0, 0])
        a = anyv.get(sha, [0, 0, 0, 0])
        wr = e[0] / e[3] if e[3] else 0.5
        ar = a[0] / a[3] if a[3] else 0.0
        return (-wr, -ar)

    order = sorted(agents, key=sort_key)

    L = []
    def p(s=""):
        L.append(s); print(s)

    p("# TOP META TABLE")
    p()
    p("Generated by `benchmark/build_meta_table.py` from the canonical per-game")
    p(f"rows in `experiments/final_meta_results.csv` "
      f"({len(rows)} rows, {len(valid)} valid, 0 self-play).")
    p()
    p("**Sorted by evidence, not by historical Kaggle score.** A notebook's")
    p("published score is context; it is not a measurement and it is not")
    p("comparable with an offline win rate. Terminology is kept strictly")
    p("separate throughout:")
    p()
    p("| term | meaning |")
    p("|---|---|")
    p("| ladder rating | the live Kaggle `publicScore` of a submission |")
    p("| validation score | Kaggle's out-of-sample estimate; a different number again |")
    p("| notebook public score | a self-reported figure in a public notebook title |")
    p("| **offline win rate** | what this table reports, measured here on ladder-derived worlds |")
    p()
    p("## 1. Main table")
    p()
    p("| agent | lineage | SHA | license | games | W-L-T | win% | "
      "Wilson 95% | median cash | max ms | vs PRIMARY | vs HEDGE | notes |")
    p("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for sha in order:
        name = label.get(sha, sha[:12])
        m = meta.get(name, {})
        w, l, t, n = anyv.get(sha, [0, 0, 0, 0])
        if sha == PRIMARY_SHA or sha == HEDGE_SHA:
            w, l, t, n = pv.get(sha, [0, 0, 0, 0])[0], pv.get(sha, [0, 0, 0, 0])[1], \
                pv.get(sha, [0, 0, 0, 0])[2], pv.get(sha, [0, 0, 0, 0])[3]
            agg = "hub"
        else:
            agg = ""
        iv = win_interval(w, l, t) if n else {"win_rate": 0, "wilson_lo": 0,
                                              "wilson_hi": 0}
        md = sorted(med.get(sha, [0]))
        medv = f"${md[len(md)//2]:,}" if md else "-"
        rts = rt.get(sha, [0])
        rtv = f"{max(rts):.0f}" if rts else "-"
        pstr, pci = cell(sha, pv)
        hstr, hci = cell(sha, hv)
        note = m.get("notes", "")[:60]
        if sha == PRIMARY_SHA:
            note = "POSTMORTEM PRIMARY"
        elif sha == HEDGE_SHA:
            note = "POSTMORTEM HEDGE - SAME LINEAGE as PRIMARY"
        p(f"| {name} | {m.get('lineage','?')[:26]} | `{sha[:12]}` | "
          f"{m.get('license','?')[:18]} | {n} | {w}-{l}-{t} | "
          f"{iv['win_rate']:.3f} | [{iv['wilson_lo']:.3f}, "
          f"{iv['wilson_hi']:.3f}] | {medv} | {rtv} | {pstr} {pci} | "
          f"{hstr} {hci} | {note} |")
    p()
    p("The `vs PRIMARY` and `vs HEDGE` columns are the evidence columns: they are")
    p("direct, paired, both-seat head-to-head records against the two agents")
    p("that matter. The `games / W-L-T / win%` columns pool every match an agent")
    p("played against anything, so they are NOT comparable between agents that")
    p("were played against different opponents.")
    p()
    p("## 2. The top-two result")
    p()
    p("| quantity | value |")
    p("|---|---|")
    p("| PRIMARY vs HEDGE, paired, both seats | **1039-945 over 1,984 games** |")
    p("| win rate | 0.5237 |")
    p("| **Wilson 95%** | **[0.5017, 0.5456]** |")
    p("| exact binomial p vs 50% | 0.0368 |")
    p("| verdict | separated from 50%, by about two points |")
    p("| seat effect (McNemar) | none, p = 0.901 |")
    p("| mean paired margin | $28, bootstrap 95% CI [-$63, $118] |")
    p("| decided by under $1,000 | 59.0% |")
    p()
    p("Full analysis in `reports/V51_VS_FARM.md`.")
    p()
    p("## 3. Lineage diversity — the acknowledged weakness")
    p()
    lin = defaultdict(list)
    for sha in order:
        lin[meta.get(label.get(sha, ""), {}).get("lineage", "?")].append(
            label.get(sha, sha[:12]))
    p("| lineage | agents |")
    p("|---|---|")
    for k, v in sorted(lin.items(), key=lambda kv: -len(kv[1])):
        p(f"| {k} | {len(v)}: {', '.join(v[:4])} |")
    p()
    p("A further search of final-period Kaggle Code for independent lineages is")
    p("recorded in `reports/RETRACTIONS.md` under NO_GO. The honest position: the")
    p("legally reusable public agent set contains essentially **one** strong")
    p("lineage, so this table cannot validate the champion against a diverse")
    p("field, and the hedge does not diversify strategy risk.")
    p()
    p("## 4. The one decisive structural finding")
    p()
    p("`benchmark/lineage_check.py`:")
    p()
    p("| | v51 | Farm 2945 |")
    p("|---|---|---|")
    p("| unique identifiers | 1,530 | 1,473 |")
    p("| shared identifiers | 1,205 | 1,205 |")
    p("| containment (min side) | 0.818 | |")
    p("| longest identical token run | **3,352** | |")
    p("| header credit list | identical nine authors | |")
    p()
    p("The PRIMARY and the HEDGE are the **same lineage**. v51 descends from the")
    p("2945 Farm. This is why 59% of their mutual games are decided by under")
    p("$1,000 and why the win rate is 52% rather than 70%: they are near-clones.")
    p()

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"\nwrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
