"""Merge round-robin shards, test BT identifiability, and publish only if valid.

The previous report published betas from a loop that had not converged. This
merges the shard CSVs, applies the identifiability gate from
`benchmark/stats.py`, and refuses to print any ranking unless the gate passes.
"""
import csv
import glob
import itertools
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "benchmark"))
from stats import (win_interval, bt_identifiability, bradley_tery,   # noqa: E402
                   bt_implied_p, wilson)

OUT_CSV = os.path.join(ROOT, "experiments", "round_robin.csv")
OUT_MD = os.path.join(ROOT, "reports", "ROUND_ROBIN.md")


def main():
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, "experiments", "rr", "*.csv"))):
        rows += list(csv.DictReader(open(f, encoding="utf-8")))
    if not rows:
        print("no round-robin rows")
        return 1
    valid = [r for r in rows if r["valid"] == "1"]
    invalid = len(rows) - len(valid)

    with open(OUT_CSV, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=rows[0].keys())
        w.writeheader()
        w.writerows(rows)

    agg = {}
    for r in valid:
        a, b = r["candidate_name"], r["opponent_name"]
        k = tuple(sorted((a, b)))
        e = agg.setdefault(k, [0, 0, 0, 0])
        wa, wb = int(r["win"]), int(r["loss"])
        e[0] += wa; e[1] += wb; e[2] += int(r["tie"]); e[3] += 1
    agents = sorted({a for k in agg for a in k})

    # Which pairs were played at all? The graph must be connected.
    edges = set(agg)
    seen, stack = set(), [agents[0]]
    while stack:
        n = stack.pop()
        if n in seen:
            continue
        seen.add(n)
        for (x, y) in edges:
            if x == n:
                stack.append(y)
            elif y == n:
                stack.append(x)
    unconnected = [a for a in agents if a not in seen]

    bt = {}
    full = {}          # every decided pair, separations INCLUDED
    separated = []
    for (a, b), (wa, lb, t, g) in sorted(agg.items()):
        first = a if a < b else b
        w2 = wa if first == a else lb
        l2 = g - w2 - t
        if t == g:
            separated.append((first, b, "all ties (same behaviour)"))
            continue
        full[(first, b)] = (w2, l2)
        if w2 == 0 or l2 == 0:
            separated.append((first, b, f"complete separation {w2}-{l2}"))
            continue
        bt[(first, b)] = (w2, l2)
    # The identifiability gate must see EVERY decided pair, including the
    # completely separated ones. Passing only the non-separated subset makes
    # every agent look isolated, which is a different and wrong diagnosis.
    ident = bt_identifiability(full, teams=agents)

    L = []
    def p(s=""):
        L.append(s); print(s)

    p("# Connected round robin")
    p()
    p(f"Generated by `benchmark/merge_round_robin.py` from "
      f"{len(rows)} per-game rows in `experiments/round_robin.csv`.")
    p()
    p(f"- agents: **{len(agents)}**")
    p(f"- pairs played: **{len(agg)}** of {len(agents)*(len(agents)-1)//2} possible")
    p(f"- valid games: **{len(valid)}**, invalid: {invalid}")
    p(f"- seeds per pair: 8, both seats")
    p()
    p("This exists because the previous measurement graph was a two-hub star in")
    p("which every bottom-tier agent lost 100% of its games, making its")
    p("maximum-likelihood strength unbounded below. These are the missing")
    p("cross-tier matches.")
    p()
    p("## Pairwise results")
    p()
    p(f"| A | B | A wins | n | Wilson 95% |")
    p("|---|---|---|---|---|")
    for (a, b), (wa, lb, t, g) in sorted(agg.items(),
                                         key=lambda kv: -kv[1][0] / max(1, kv[1][3])):
        first = a if a < b else b
        w2 = wa if first == a else lb
        lo, hi = wilson(w2, g - t)
        p(f"| {first} | {b} | {w2}-{g-w2-t} | {g} | "
          f"[{lo:.3f}, {hi:.3f}] |")
    p()
    p("## Identifiability")
    p()
    p(f"- strong component size: **{ident['strong_component_size']} of "
      f"{ident['teams']}**")
    p(f"- graph connected: **{not ident['disconnected']}**")
    p(f"- agents with 0 wins (MLE = -inf): {ident['zero_win'] or 'none'}")
    p(f"- agents with 0 losses (MLE = +inf): {ident['zero_loss'] or 'none'}")
    p(f"- agents never played: {ident['isolated'] or 'none'}")
    p(f"- agents outside the strong component: "
      f"{unconnected or 'none'}")
    p()
    if separated:
        p("Pairs still fully separated (excluded from the fit):")
        p()
        for a, b, why in separated:
            p(f"- `{a}` vs `{b}`: {why}")
        p()

    if ident["ok"]:
        beta = bradley_tery(bt)
        p("## Bradley-Terry (finite MLE, identifiability gate PASSED)")
        p()
        p(f"| agent | beta |")
        p("|---|---|")
        for t_, v in sorted(beta.items(), key=lambda kv: -kv[1]):
            p(f"| {t_} | {v:.3f} |")
        p()
        p("Implied head-to-heads (model output next to the observed rate):")
        p()
        order = sorted(beta, key=lambda k: -beta[k])
        for i, x in enumerate(order):
            for y in order[i + 1:]:
                k = (x, y) if (x, y) in bt else (y, x)
                if k in bt:
                    lo, hi = wilson(bt[k][0], bt[k][0] + bt[k][1])
                    tie = "" if (hi < 0.5 or lo > 0.5) else "  <- observed rate spans 50%"
                    p(f"- P({x} > {y}) = **{bt_implied_p(beta,x,y):.3f}**  "
                      f"observed {bt[k][0]}-{bt[k][1]}{tie}")
        p()
        p("Betas are an OFFLINE estimate over a self-selected league. They are")
        p("not a Kaggle rating, not a validation score, and not calibrated to")
        p("either.")
    else:
        p("## REGULARIZED BT (MAP, Normal(0, 1) prior) — plain MLE withheld")
        p()
        p("The identifiability gate **FAILED**, so no plain-MLE betas are")
        p("published. The league is a strict linear order: the top group wins")
        p("every game it plays and the bottom group loses every game, so the")
        p("maximum-likelihood strengths are unbounded and the log-likelihood has")
        p("no finite maximum.")
        p()
        p("A prior is what makes a finite optimum exist. The ranking below is")
        p("therefore **REGULARIZED BT**, a MAP estimate under a Normal(0, 1)")
        p("prior on the betas, fitted on the non-separated pairs. The prior")
        p("shrinks every beta toward 0, so the *spread is compressed* and the")
        p("absolute values are not comparable with an MLE fit.")
        p()
        from stats import bradley_tery_regularized
        reg = bradley_tery_regularized(full)
        p(f"| agent | regularized beta | games | W | L |")
        p("|---|---|---|---|---|")
        for t_ in sorted(reg, key=lambda k: -reg[k]):
            gw = gl = gg = 0
            for (a, b), (wa, wb) in full.items():
                if t_ == a:
                    gw += wa; gl += wb; gg += wa + wb
                elif t_ == b:
                    gw += wb; gl += wa; gg += wa + wb
            p(f"| {t_} | {reg[t_]:.3f} | {gg} | {gw} | {gl} |")
        p()
        p("**Only the ordering is meaningful.** The primary evidence for any")
        p("pair remains its observed head-to-head record with its Wilson")
        p("interval in the table above, not a beta.")
    p()

    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"\nwrote {os.path.relpath(OUT_CSV, ROOT)} and "
          f"{os.path.relpath(OUT_MD, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
